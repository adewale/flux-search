#!/usr/bin/env node
/**
 * Build a tiny English Zipf-frequency table for Flux topic scoring.
 *
 * Data source: nodewordfreq, which reuses Robyn Speer's wordfreq data.
 * See docs/background-frequency-attribution.md for attribution and source
 * license notes. This script is intentionally offline/build-time only; the
 * Worker imports only the generated table.
 */
import { writeFileSync, readFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { zipfFrequency } from 'nodewordfreq';

const extraTerms = new Set([
  'systems thinking', 'many americans', 'mental models', 'complex times',
  'large language models', 'world war', 'good ideas', 'open source', 'air force',
  'crypto', 'cryptocurrency', 'rest of world', 'not boring', 'crooked timber',
  'simple habits for complex times', 'seeing like a state', 'climate change',
  'machine learning', 'new york', 'new york city', 'united states',
]);

for (const f of readdirSync('data/processed').filter(f => f.endsWith('.json'))) {
  const issue = JSON.parse(readFileSync(join('data/processed', f), 'utf8'));
  for (const field of ['title', 'subtitle', 'lead_essay_title']) {
    const value = issue[field];
    if (typeof value === 'string') extraTerms.add(value.toLowerCase());
  }
}

function tokens(term) {
  return term.toLowerCase().match(/[a-z][a-z0-9'-]*/g) ?? [];
}

const terms = new Set();
for (const term of extraTerms) {
  const normalized = tokens(term).join(' ');
  if (!normalized) continue;
  terms.add(normalized);
  for (const token of tokens(normalized)) terms.add(token);
}

const entries = [...terms]
  .map(term => [term, Number(zipfFrequency(term, 'en').toFixed(3))])
  .filter(([, zipf]) => Number.isFinite(zipf) && zipf > 0)
  .sort(([a], [b]) => a.localeCompare(b));

const body = `/**\n * Generated by scripts/build-background-frequency.mjs. Do not edit by hand.\n *\n * Source: nodewordfreq@0.2.1, a Node/TypeScript port of Robyn Speer's\n * wordfreq data/API. See docs/background-frequency-attribution.md.\n */\nexport const BACKGROUND_ZIPF_EN: Readonly<Record<string, number>> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};\n`;

writeFileSync('src/lib/background-frequency.generated.ts', body);

const sha256 = createHash('sha256').update(body).digest('hex');
const manifest = {
  generated_at: new Date().toISOString(),
  generator: 'scripts/build-background-frequency.mjs',
  output: 'src/lib/background-frequency.generated.ts',
  output_sha256: sha256,
  terms: entries.length,
  source_package: 'nodewordfreq',
  source_version: '0.2.1',
  source_repository: 'https://github.com/realchendahuang/nodewordfreq',
  upstream_package: 'wordfreq',
  upstream_repository: 'https://github.com/rspeer/wordfreq',
  language: 'en',
  frequency_measure: 'Zipf frequency',
  runtime_dependency: false,
  attribution: 'docs/background-frequency-attribution.md',
  license_notes: [
    'nodewordfreq package code declares Apache-2.0.',
    'nodewordfreq reuses Python wordfreq data files.',
    'wordfreq data includes mixed sources and Creative Commons Attribution-ShareAlike 4.0 material; preserve attribution notes.',
  ],
};
writeFileSync('data/background/manifest.json', `${JSON.stringify(manifest, null, 2)}\n`);

console.log(JSON.stringify({
  terms: entries.length,
  output: 'src/lib/background-frequency.generated.ts',
  manifest: 'data/background/manifest.json',
}, null, 2));
